"""
Generate the bundled sample cohort (assets/sample_cohort.csv) and its data dictionary.

Synthetic, fully documented, deterministic (seed 2026). Designed so every analysis page has
something meaningful to show: a binary outcome with a real treatment effect, a prognostic
score, time-to-event data, documented MCAR and MAR missingness, a Bland-Altman pair,
day-first dates and one deliberate data-entry anomaly (age = 212).

    python dev_scripts/make_sample_cohort.py
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

SEED = 2026
N = 500
ROOT = Path(__file__).resolve().parents[1]
CSV_PATH = ROOT / "assets" / "sample_cohort.csv"
DICT_PATH = ROOT / "assets" / "sample_cohort_dictionary.md"


def make_sample_cohort(n: int = N, seed: int = SEED) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    arm = rng.choice(["Placebo", "Treatment"], size=n)
    is_placebo = arm == "Placebo"
    age = np.clip(rng.normal(62, 11, n), 25, 90).round().astype(int)
    sex = rng.choice(["F", "M"], size=n)
    bmi = np.clip(rng.normal(27, 4.5, n), 16, 48).round(1)
    smoker = rng.choice(["No", "Yes"], size=n, p=[0.7, 0.3])
    is_smoker = smoker == "Yes"
    sbp = (rng.normal(135, 16, n) + 6 * is_smoker).round().astype(int)
    stage = rng.choice(["I", "II", "III", "IV"], size=n, p=[0.30, 0.35, 0.25, 0.10])
    stage_idx = pd.Categorical(stage, categories=["I", "II", "III", "IV"]).codes
    site = rng.choice(["Luxembourg", "Esch-sur-Alzette", "Ettelbruck"], size=n, p=[0.5, 0.3, 0.2])

    # Binary outcome: placebo roughly doubles the risk (RR about 2), stage and smoking add risk.
    logit = -1.7 + 1.05 * is_placebo + 0.35 * stage_idx + 0.02 * (age - 62) + 0.4 * is_smoker
    p_event = 1 / (1 + np.exp(-logit))
    event_flag = rng.random(n) < p_event
    event = np.where(event_flag, "Yes", "No")

    # Prognostic score with AUC about 0.80 for the event.
    score = np.where(event_flag, rng.normal(0.62, 0.18, n), rng.normal(0.40, 0.18, n))
    score = np.clip(score, 0, 1).round(3)

    # Biomarker (log-normal, rises with stage) with MAR missingness: more often missing in the Treatment arm.
    biomarker = np.exp(np.log(50) + 0.2 * stage_idx + rng.normal(0, 0.5, n)).round(2)
    mar_missing = rng.random(n) < np.where(is_placebo, 0.05, 0.25)
    biomarker = np.where(mar_missing, np.nan, biomarker)

    # Laboratory value with 8 % MCAR missingness.
    lab_mcar = rng.normal(4.5, 0.8, n).round(2)
    lab_mcar = np.where(rng.random(n) < 0.08, np.nan, lab_mcar)

    # Time to event (days): exponential survival, uniform censoring.
    true_time = rng.exponential(np.where(is_placebo, 550, 900), n)
    censor = rng.uniform(200, 1095, n)
    fu_days = np.minimum(true_time, censor).round().astype(int)
    died = np.where(true_time <= censor, "Yes", "No")

    # Two measurement methods for Bland-Altman (method B reads 1.5 units higher on average).
    method_a = rng.normal(100, 15, n).round(1)
    method_b = (method_a + 1.5 + rng.normal(0, 4, n)).round(1)

    # Day-first enrolment dates (dd/mm/yyyy) between 2021 and 2023.
    start = pd.Timestamp("2021-01-01")
    enrol = start + pd.to_timedelta(rng.integers(0, 3 * 365, n), unit="D")
    enrol_date = enrol.strftime("%d/%m/%Y")

    rare_binary = rng.choice(["No", "Yes"], size=n, p=[0.97, 0.03])

    df = pd.DataFrame({
        "patient_id": [f"P{1001 + i}" for i in range(n)],
        "site": site,
        "enrol_date": enrol_date,
        "arm": arm,
        "age": age,
        "sex": sex,
        "bmi": bmi,
        "smoker": smoker,
        "sbp": sbp,
        "stage": stage,
        "biomarker": biomarker,
        "lab_mcar": lab_mcar,
        "score": score,
        "event": event,
        "fu_days": fu_days,
        "died": died,
        "method_a": method_a,
        "method_b": method_b,
        "rare_binary": rare_binary,
    })
    # One deliberate data-entry anomaly for the validation page to find.
    df.loc[17, "age"] = 212
    return df


DICTIONARY = """# Sample cohort - data dictionary

Synthetic data generated by `dev_scripts/make_sample_cohort.py` (seed 2026, n = 500).
No real patients. Use it to try every page before loading your own cohort.

| Column | Type | Meaning | Notes |
|---|---|---|---|
| patient_id | identifier | Pseudonymous patient code | unique |
| site | categorical | Recruiting site | 3 levels |
| enrol_date | date (dd/mm/yyyy) | Enrolment date | **day-first** format; set "day first" when importing |
| arm | categorical | Study arm | Placebo / Treatment; Placebo roughly doubles the event risk |
| age | numeric (years) | Age at enrolment | **one deliberate anomaly: 212** (row 18) |
| sex | categorical | Sex | F / M |
| bmi | numeric (kg/m2) | Body-mass index | |
| smoker | binary | Current smoker | No / Yes |
| sbp | numeric (mmHg) | Systolic blood pressure | higher in smokers |
| stage | ordinal | Disease stage | I < II < III < IV |
| biomarker | numeric | Serum biomarker (log-normal) | **MAR missingness**: missing more often in the Treatment arm |
| lab_mcar | numeric | Laboratory value | **MCAR missingness** (about 8 %) |
| score | numeric 0-1 | Prognostic score | AUC about 0.80 for `event` |
| event | binary | Primary outcome | No / Yes |
| fu_days | numeric (days) | Follow-up time | time to `died` or censoring |
| died | binary | Death during follow-up | No / Yes (event indicator for survival analysis) |
| method_a, method_b | numeric | Same quantity measured by two methods | method_b reads about +1.5 on average (Bland-Altman) |
| rare_binary | binary | Rare condition (about 3 %) | small expected counts: Fisher's exact test territory |

Suggested walk-through: Validate (finds the age anomaly and the missingness pattern) ->
Explore (descriptives, correlations) -> Analyze (`arm` x `event`: relative risk about 2;
`score` vs `event`: diagnostic accuracy) -> Visualize (`method_a` vs `method_b`).
"""


def main() -> None:
    df = make_sample_cohort()
    CSV_PATH.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(CSV_PATH, index=False)
    DICT_PATH.write_text(DICTIONARY, encoding="utf-8")
    print(f"wrote {CSV_PATH} ({len(df)} rows, {df.shape[1]} columns) and {DICT_PATH}")


if __name__ == "__main__":
    main()
